-- WalkLog.java 엔티티의 @Column 매핑과 정확히 일치하는 walk_log 테이블 정의
-- ddl-auto=validate는 테이블을 자동 생성하지 않으므로, 서버 기동 시 이 스크립트로 먼저 테이블을 만들고
-- 그 뒤에 Hibernate가 엔티티와 실제 스키마가 일치하는지 검증하는 방식으로 동작함
-- (spring.sql.init.mode=always 설정 시, defer-datasource-initialization 기본값(false) 덕분에
--  Hibernate 초기화보다 먼저 실행됨)
CREATE TABLE IF NOT EXISTS walk_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(id), -- navigation 테이블과 동일하게 users(id) 참조 FK 유지
    route_data      JSONB NOT NULL, -- navigation.route_data와 동일하게 @JdbcTypeCode(SqlTypes.JSON)로 jsonb 매핑
    total_distance  DOUBLE PRECISION NOT NULL,
    total_time      BIGINT NOT NULL,
    obstacle_count  INTEGER NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL
);
