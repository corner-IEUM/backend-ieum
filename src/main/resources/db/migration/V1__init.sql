-- 초기 스키마: users, navigation, walk_log, crosswalks
-- ddl-auto=update로 임시 생성되어 있던 users/navigation/walk_log, 그리고 수동으로 적재된
-- crosswalks를 Flyway로 일원화한 베이스라인.
-- 기존 환경(로컬/운영)에 이미 테이블이 있어도 깨지지 않도록 CREATE TABLE IF NOT EXISTS로 작성함.

-- ===================== users =====================
CREATE TABLE IF NOT EXISTS users
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       VARCHAR(100) NOT NULL UNIQUE,
    password    VARCHAR(255) NOT NULL,
    nickname    VARCHAR(50)  NOT NULL,
    create_date TIMESTAMP(6) NOT NULL,
    status      VARCHAR(20)  NOT NULL, -- UserStatus: ACTIVE, INACTIVE, BANNED, DELETED
    role        VARCHAR(20)  NOT NULL  -- Role: USER, ADMIN
);

-- ===================== navigation =====================
CREATE TABLE IF NOT EXISTS navigation
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT           NOT NULL REFERENCES users (id),
    start_lng     DOUBLE PRECISION NOT NULL,
    start_lat     DOUBLE PRECISION NOT NULL,
    end_lng       DOUBLE PRECISION NOT NULL,
    end_lat       DOUBLE PRECISION NOT NULL,
    route_data    JSONB            NOT NULL,
    distance      INTEGER          NOT NULL,
    duration      INTEGER          NOT NULL,
    start_time    TIMESTAMP(6)     NOT NULL,
    end_time      TIMESTAMP(6),
    obstacle_cnt  INTEGER          NOT NULL,
    completed     BOOLEAN          NOT NULL
);

-- ===================== walk_log =====================
-- 기존 schema.sql 내용을 그대로 이관
CREATE TABLE IF NOT EXISTS walk_log
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT           NOT NULL REFERENCES users (id),
    route_data     JSONB            NOT NULL,
    total_distance DOUBLE PRECISION NOT NULL,
    total_time     BIGINT           NOT NULL,
    obstacle_count INTEGER          NOT NULL,
    created_at     TIMESTAMP(6)     NOT NULL
);

-- ===================== crosswalks =====================
-- 전국횡단보도표준데이터 (팀원 관리, PostGIS geography 컬럼 사용)
CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS crosswalks
(
    id                    BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    management_no         VARCHAR(255),
    location              GEOGRAPHY(Point, 4326) NOT NULL,
    has_curb_cut          BOOLEAN,
    has_braille_block     BOOLEAN,
    has_sound_signal      BOOLEAN,
    has_pedestrian_signal BOOLEAN,
    width_m               DOUBLE PRECISION,
    raw_data              JSONB,
    created_at            TIMESTAMP NOT NULL DEFAULT now(),
    source_updated_at     DATE,
    raised_crosswalk      BOOLEAN,
    crossing_length_m     DOUBLE PRECISION,
    green_signal_sec      DOUBLE PRECISION
);

ALTER TABLE IF EXISTS crosswalks OWNER TO ieum_user;

CREATE INDEX IF NOT EXISTS idx_crosswalks_location
    ON crosswalks USING gist (location);
